using AI.CAS.Core.Ast;
using System.Collections.Immutable;

/// <summary>
/// Задает общий неизменяемый контракт атомарной символической константы типизированного Ast.
/// Этот базовый тип не хранит имя, числовое значение или строковый дискриминатор: семантика конкретной константы
/// определяется только CLR-типом наследника, например <see cref="AstPiNode"/> или <see cref="AstImaginaryUnitNode"/>.
/// </summary>
public abstract class AstSymbolicConstantNode : AstNode
{
    /// <summary>
    /// Возвращает пустую неизменяемую коллекцию детей.
    /// Символическая константа всегда является листом, поэтому свойство закреплено в базовом типе этого семейства
    /// и не может быть переопределено наследниками с другой арностью.
    /// </summary>
    public sealed override ImmutableArray<AstNode> Children { get; } = ImmutableArray<AstNode>.Empty;


    /// <summary>
    /// Создает атомарную символическую константу без дочерних узлов.
    /// Конструктор не принимает данных, потому что конкретный CLR-тип уже полностью задает смысл атома: у <c>pi</c>,
    /// <c>e</c>, <c>i</c> и бесконечностей нет операндов, аргументов или строкового значения на уровне Ast.
    /// </summary>
    protected AstSymbolicConstantNode()
    {
    }


    /// <summary>
    /// Перестраивает атомарную константу через общий маршрут <see cref="AstNode.WithChildren(ImmutableArray{AstNode})"/>.
    /// Метод допускает только пустую коллекцию детей: добавление ребенка к константе изменило бы математическую
    /// категорию узла и нарушило бы инвариант атомарности. При пустой коллекции создается новый узел того же
    /// конкретного типа, чтобы общий функциональный API оставался неизменяемым и детерминированным.
    /// </summary>
    /// <param name="children">
    /// Новая коллекция детей. Для символической константы она обязана быть пустой.
    /// </param>
    /// <returns>
    /// Новый атомарный узел того же конкретного CLR-типа.
    /// </returns>
    public sealed override AstNode WithChildren(ImmutableArray<AstNode> children)
    {
        // Проверяем, что вызывающий код не передал неинициализированную коллекцию или null-элементы в общей коллекционной форме.
        ValidateChildren(children, nameof(children));

        // Запрещаем любые дочерние узлы, потому что символическая константа является атомом, а не функцией или операцией.
        if (!children.IsEmpty)
        {
            // Сообщаем об ошибке арности на границе AST, чтобы дальнейшие CAS-слои не получили невалидную структуру.
            throw new ArgumentException("Символическая константа AST не может иметь дочерние узлы.", nameof(children));
        }

        // Создаем новый атом того же конкретного типа, сохраняя функциональный стиль перестроения AST.
        return Recreate();
    }


    /// <summary>
    /// Создает новый экземпляр того же конкретного типа символической константы.
    /// Базовый класс вызывает этот метод после проверки пустой коллекции детей, а наследник выбирает конкретный
    /// CLR-тип результата без строкового имени и без условной логики по виду константы.
    /// </summary>
    /// <returns>
    /// Новый атомарный узел той же символической константы.
    /// </returns>
    protected abstract AstSymbolicConstantNode Recreate();
}
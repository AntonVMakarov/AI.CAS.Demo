namespace AI.CAS.Core.Assumptions;

/// <summary>
/// Перечисляет базовые виды предикатов, которые могут быть сохранены в наборе предположений.
/// На первом этапе эти значения являются только декларативными ключами фактов и запросов, а не правилами вывода.
/// </summary>
public enum AssumptionPredicateKind
{
    /// <summary>
    /// Выражение принадлежит указанной математической области.
    /// </summary>
    DomainMember = 0,


    /// <summary>
    /// Выражение не равно нулю.
    /// </summary>
    NonZero = 1,


    /// <summary>
    /// Выражение известно как вещественное значение, строго большее нуля.
    /// Этот предикат относится только к обычной конечной вещественной прямой. Поэтому <c>+∞</c>
    /// не является <see cref="Positive"/>: для него используется отдельный расширенный предикат
    /// <see cref="ExtendedPositive"/>.
    /// </summary>
    Positive = 2,


    /// <summary>
    /// Выражение известно как вещественное значение, строго меньшее нуля.
    /// Как и <see cref="Positive"/>, этот предикат описывает только конечные вещественные значения. Поэтому
    /// <c>-∞</c> не является <see cref="Negative"/> и должен описываться через <see cref="ExtendedNegative"/>.
    /// </summary>
    Negative = 3,


    /// <summary>
    /// Выражение является конечным вещественным числом.
    /// Расширенные вещественные значения <c>+∞</c> и <c>-∞</c> не являются <see cref="Real"/> и должны
    /// описываться через <see cref="ExtendedReal"/>.
    /// </summary>
    Real = 4,


    /// <summary>
    /// Выражение является целым.
    /// </summary>
    Integer = 5,


    /// <summary>
    /// Выражение является конечным значением.
    /// </summary>
    Finite = 6,


    /// <summary>
    /// Выражение равно другому выражению.
    /// </summary>
    Equal = 7,


    /// <summary>
    /// Выражение не равно другому выражению.
    /// </summary>
    NotEqual = 8,


    /// <summary>
    /// Выражение в точности равно нулю.
    /// Этот предикат является атомарным утверждением о самом выражении и сам по себе не добавляет
    /// анализа составных форм вроде <c>x - x</c>, <c>x * 0</c> или предельных случаев функций.
    /// </summary>
    Zero = 9,


    /// <summary>
    /// Выражение известно как вещественное значение, большее либо равное нулю.
    /// Важная часть смысла предиката — вещественность: для комплексных или неизвестных областей утверждение
    /// <c>NonNegative</c> не должно выводиться без отдельного безопасного доказательства. Это также
    /// конечная вещественность, поэтому <c>+∞</c> описывается через <see cref="ExtendedNonNegative"/>, а не
    /// через этот обычный предикат.
    /// </summary>
    NonNegative = 10,


    /// <summary>
    /// Выражение известно как вещественное значение, меньшее либо равное нулю.
    /// Предикат не означает отрицательность: ноль одновременно является неотрицательным и неположительным,
    /// поэтому обратное усиление до строгого знака запрещено без отдельного правила. Как и остальные обычные
    /// знаковые предикаты, он относится только к конечной вещественной прямой.
    /// </summary>
    NonPositive = 11,


    /// <summary>
    /// Выражение известно как неконечное значение.
    /// Предикат нужен для явного различения конечности и неконечности, например для стандартных узлов
    /// бесконечности, но не вводит новую арифметику расширенной числовой прямой.
    /// </summary>
    NonFinite = 12,


    /// <summary>
    /// Выражение принадлежит расширенной вещественной прямой.
    /// Сюда входят конечные вещественные числа, <c>+∞</c> и <c>-∞</c>. Комплексная бесконечность
    /// <c>cinf</c> не является расширенным вещественным значением.
    /// </summary>
    ExtendedReal = 13,


    /// <summary>
    /// Выражение является положительным значением расширенной вещественной прямой.
    /// Предикат покрывает обычные положительные конечные числа и <c>+∞</c>, но сам по себе не доказывает
    /// обычную конечную положительность.
    /// </summary>
    ExtendedPositive = 14,


    /// <summary>
    /// Выражение является отрицательным значением расширенной вещественной прямой.
    /// Предикат покрывает обычные отрицательные конечные числа и <c>-∞</c>, но не доказывает обычную конечную
    /// отрицательность.
    /// </summary>
    ExtendedNegative = 15,


    /// <summary>
    /// Выражение является неотрицательным значением расширенной вещественной прямой.
    /// В частности, <c>0</c>, положительные конечные числа и <c>+∞</c> удовлетворяют этому предикату.
    /// </summary>
    ExtendedNonNegative = 16,


    /// <summary>
    /// Выражение является неположительным значением расширенной вещественной прямой.
    /// В частности, <c>0</c>, отрицательные конечные числа и <c>-∞</c> удовлетворяют этому предикату.
    /// </summary>
    ExtendedNonPositive = 17,


    /// <summary>
    /// Выражение принадлежит точному типизированному скалярному интервалу.
    /// Интервал хранится в <see cref="AssumptionAtom.Interval"/>, а не в строке, не во втором выражении
    /// и не в доменной области, потому что открытость и закрытость endpoint являются математическими данными.
    /// </summary>
    InInterval = 18,


    /// <summary>
    /// Выражение принадлежит образу главной ветви комплексного логарифма.
    /// Для значения <c>c</c> это означает условие <c>-pi &lt; Im(c) &lt;= pi</c> в соглашении CAS
    /// <c>Arg(z) in (-pi, pi]</c>. Предикат добавлен как отдельное типизированное утверждение, потому что
    /// текущий Ast не имеет безопасного первого класса для <c>Im(c)</c>, а строковое условие разрушило бы
    /// машинную семантику условных результатов Solve.
    /// </summary>
    PrincipalLogImageStrip = 19
}

namespace AI.CAS.Core.Assumptions;

/// <summary>
/// Перечисляет семантические виды границы скалярного интервала.
/// Значения описывают математический смысл границы, а не способ ее отображения в строке. Это важно для
/// доказательств вида <c>x in [-1, 1]</c>: закрытая граница допускает равенство с концом, открытая граница
/// требует строгой внутренней стороны, а неограниченная граница вообще не создает endpoint-обязательство.
/// </summary>
public enum ScalarIntervalBoundKind
{
    /// <summary>
    /// Граница отсутствует и соответствующая сторона интервала не ограничена.
    /// Такая граница не хранит endpoint и не должна превращаться в строку вроде <c>+inf</c> или <c>-inf</c>,
    /// потому что направление задается позицией границы внутри <see cref="ScalarInterval"/>.
    /// </summary>
    Unbounded = 0,


    /// <summary>
    /// Конечная открытая граница.
    /// Endpoint хранится как точный неизменяемый Ast узел, а принадлежность endpoint самому интервалу запрещена.
    /// </summary>
    Open = 1,


    /// <summary>
    /// Конечная закрытая граница.
    /// Endpoint хранится как точный неизменяемый Ast узел, а равенство с endpoint входит в интервал.
    /// </summary>
    Closed = 2
}
namespace AI.CAS.Core.Domains;

/// <summary>
/// Определяет общий вид математической области.
/// Значение этого перечисления является классификатором контекста, а не доказательством принадлежности
/// конкретного выражения области.
/// </summary>
public enum DomainKind
{
    /// <summary>
    /// Область комплексных чисел.
    /// Это самый широкий стандартный скалярный контекст для большинства текущих преобразований без пошагового вывода.
    /// </summary>
    Complex = 0,


    /// <summary>
    /// Область вещественных чисел.
    /// Эта область должна использоваться только тогда, когда запрос или будущий механизм предположений
    /// явно задает вещественный контекст.
    /// </summary>
    Real = 1,


    /// <summary>
    /// Область рациональных чисел.
    /// Она нужна для будущих полиномиальных и алгебраических алгоритмов, где рациональность коэффициентов
    /// является отдельным математическим условием.
    /// </summary>
    Rational = 2,


    /// <summary>
    /// Область целых чисел.
    /// Эта область будет важна для диофантовых задач, факторизации и проверок целочисленных параметров.
    /// </summary>
    Integer = 3,


    /// <summary>
    /// Область натуральных чисел.
    /// На первом этапе это только маркер области. Вопрос включения нуля должен решаться будущим
    /// доменным модулем явно, а не неявным предположением в этом перечислении.
    /// </summary>
    Natural = 4,


    /// <summary>
    /// Булева область.
    /// Она предназначена для логических выражений, таблиц истинности и будущих условных конструкций.
    /// </summary>
    Boolean = 5,


    /// <summary>
    /// Область полиномиального кольца.
    /// На первом этапе это общий классификатор для будущих алгебраических контекстов, а не полноценное
    /// описание кольца коэффициентов и набора переменных.
    /// </summary>
    PolynomialRing = 6,


    /// <summary>
    /// Область матриц.
    /// Подробные параметры матричной области, такие как размерность и область элементов, должны быть
    /// представлены будущими специализированными объектами, а не только этим значением.
    /// </summary>
    Matrix = 7,


    /// <summary>
    /// Локальная область рядов.
    /// Такая область понадобится для разложений около точки, где важны порядок, направление и локальные условия.
    /// </summary>
    LocalSeries = 8,


    /// <summary>
    /// Расширенная вещественная область.
    /// Она содержит конечные вещественные числа и две направленные бесконечности <c>+∞</c> и <c>-∞</c>,
    /// но не содержит комплексную бесконечность и не является подобластью комплексных чисел.
    /// </summary>
    ExtendedReal = 9,


    /// <summary>
    /// Неизвестная область.
    /// Это безопасное значение для случаев, когда система не должна делать никаких математических выводов
    /// о допустимых значениях выражения.
    /// </summary>
    Unknown = 100
}

/// <summary>
/// Перечисляет объяснимые виды ответа механизма предположений.
/// Вид ответа является более точной причиной публичного значения <see cref="AssumptionTruthValue"/>.
/// Значение <see cref="AssumptionTruthValue.Unknown"/> намеренно разбивается на несколько случаев, потому что
/// для потребителя CAS различаются полное отсутствие свидетельств, незавершенное применимое доказательство и
/// настоящий конфликт между определенными источниками.
/// </summary>
public enum AssumptionAnswerKind
{
    /// <summary>
    /// Ни один поставщик предположений не нашел релевантных свидетельств для запроса.
    /// Такой ответ проецируется в Unknown, но отличается от незавершенности тем, что ни один применимый источник
    /// даже не начал доказательство данного утверждения.
    /// </summary>
    NoEvidence = 0,


    /// <summary>
    /// Запрос был доказан как True или False.
    /// Этот вид никогда не должен использоваться с публичным значением Unknown, потому что Unknown не является
    /// доказательством и не должен выглядеть как успешный вывод.
    /// </summary>
    Proved = 1,


    /// <summary>
    /// Хотя бы один поставщик распознал применимую форму, но не смог доказать необходимые предпосылки.
    /// Например, алгебраическое правило может увидеть произведение, но не доказать знаки и конечность всех
    /// множителей. Публичная истинность при этом остается Unknown.
    /// </summary>
    Inconclusive = 2,


    /// <summary>
    /// Независимые источники дали несовместимые определенные ответы или один поставщик обнаружил внутренний конфликт.
    /// Конфликт также проецируется в Unknown, потому что консервативный фасад не имеет права выбирать одну сторону
    /// без отдельной политики разрешения противоречий.
    /// </summary>
    Conflict = 3
}
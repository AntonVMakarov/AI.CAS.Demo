using AI.CAS.Core.Ast;
using System.Collections.ObjectModel;

namespace AI.CAS.Core.Assumptions;

/// <summary>
/// Представляет неизменяемый снимок фактов предположений для CAS.
/// Набор фактов отделен от механизма вывода, чтобы будущие модули упрощения, решения уравнений
/// и анализа областей могли передавать один и тот же контекст без скрытой мутации и без зависимости
/// от конкретной стратегии логического вывода.
/// </summary>
public sealed class AssumptionSet
{
    /// <summary>
    /// Возвращает общий пустой набор предположений.
    /// Пустой набор означает отсутствие дополнительных знаний, а не отрицание каких-либо математических свойств.
    /// </summary>
    public static AssumptionSet Empty { get; } = new AssumptionSet();


    /// <summary>
    /// Создает неизменяемый набор предположений из переданной коллекции фактов.
    /// Коллекция копируется немедленно, чтобы дальнейшие изменения внешнего списка не могли изменить
    /// математический контекст уже созданного запроса или результата.
    /// </summary>
    /// <param name="facts">
    /// Последовательность фактов предположений.
    /// Значение <c>null</c> трактуется как пустая последовательность.
    /// </param>
    /// <exception cref="ArgumentException">
    /// Возникает, если последовательность содержит отсутствующий факт.
    /// </exception>
    public AssumptionSet(IEnumerable<AssumptionFact>? facts = null)
    {
        Facts = CopyFacts(facts);
    }


    /// <summary>
    /// Возвращает неизменяемый список фактов предположений.
    /// Список никогда не равен <c>null</c>, поэтому вызывающие модули могут безопасно обходить его
    /// даже в полностью неизвестном математическом контексте.
    /// </summary>
    public IReadOnlyList<AssumptionFact> Facts { get; }


    /// <summary>
    /// Возвращает новый набор предположений, который содержит все факты текущего снимка и один дополнительный факт.
    /// Метод намеренно использует форму имени <c>WithAddedFact</c>, а не <c>Add</c>, потому что объект
    /// <see cref="AssumptionSet"/> является неизменяемым контейнером: вызов не меняет текущий экземпляр, а создает
    /// следующий снимок с расширенным списком явно заданных фактов.
    ///
    /// Добавление именно расширяет снимок, а не заменяет его содержимое.
    /// Например, если текущий набор уже хранит факт <c>x Positive True</c>, а вызывающий код добавляет
    /// <c>x Real True</c>, новый набор должен содержать оба факта. Это важно для будущих механизмов объяснения:
    /// они смогут видеть все явно переданные сведения, а не только последнее расширение контекста.
    ///
    /// Метод не выполняет дедупликацию и не проверяет противоречия. Если вызывающий код добавит два одинаковых
    /// факта или конфликтующие факты, контейнер сохранит их как явные данные, а интерпретация останется задачей
    /// <see cref="IAssumptionEngine"/> или будущего диагностического слоя.
    /// </summary>
    /// <param name="fact">
    /// Факт, который нужно добавить к новому снимку предположений.
    /// </param>
    /// <returns>
    /// Новый неизменяемый снимок, содержащий прежние факты и переданный дополнительный факт.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    /// Возникает, если добавляемый факт отсутствует.
    /// </exception>
    public AssumptionSet WithAddedFact(AssumptionFact fact)
    {
        ArgumentNullException.ThrowIfNull(fact);

        return WithAddedFacts([fact]);
    }


    /// <summary>
    /// Возвращает новый набор предположений, который содержит все факты текущего снимка и все переданные
    /// дополнительные факты в порядке их перечисления.
    /// Метод не изменяет текущий экземпляр, потому что набор предположений является снимком, привязанным к запросу:
    /// один модуль CAS может продолжать использовать старый контекст, пока другой модуль строит расширенный
    /// контекст для более узкого подвычисления.
    ///
    /// Семантика метода — именно добавление к существующему снимку.
    /// Переданная последовательность не заменяет старые факты, потому что предположения обычно накапливаются:
    /// базовый запрос может знать <c>x Real True</c>, а локальная ветка вычисления может временно добавить
    /// <c>x NonZero True</c>. Новый снимок должен сохранить оба утверждения, иначе локальное расширение случайно
    /// уничтожило бы более ранние знания.
    ///
    /// Последовательность копируется через тот же защитный путь, что и конструктор, поэтому дальнейшая мутация
    /// внешнего списка не меняет созданный <see cref="AssumptionSet"/>. Это защищает внутренний список фактов
    /// от публикации наружу: вызывающий код получает только представление снимка для чтения, а не ссылку на
    /// изменяемую коллекцию, из которой можно было бы незаметно изменить математический контекст.
    /// </summary>
    /// <param name="facts">
    /// Последовательность фактов, которые нужно добавить после уже существующих фактов.
    /// </param>
    /// <returns>
    /// Новый неизменяемый снимок с прежними фактами и добавленными фактами.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    /// Возникает, если последовательность добавляемых фактов отсутствует.
    /// </exception>
    /// <exception cref="ArgumentException">
    /// Возникает, если последовательность содержит отсутствующий факт.
    /// </exception>
    public AssumptionSet WithAddedFacts(IEnumerable<AssumptionFact> facts)
    {
        ArgumentNullException.ThrowIfNull(facts);

        return new AssumptionSet(Facts.Concat(facts));
    }


    /// <summary>
    /// Проверяет, содержит ли снимок буквально такой же факт предположений.
    /// Это точный поиск по сохраненным данным, а не математический вывод: метод не доказывает следствия,
    /// не нормализует выражения, не использует доменные включения и не превращает один предикат в другой.
    /// Например, наличие факта <c>x Positive True</c> не делает результат поиска факта <c>x NonZero True</c>
    /// истинным, хотя такая импликация может появиться в будущей фазе специализированного механизма вывода.
    ///
    /// Под точностью здесь понимается равенство всего объекта <see cref="AssumptionFact"/>: субъекта, предиката,
    /// истинностного значения, второго выражения для бинарных предикатов и области. Контейнер отвечает только
    /// на вопрос "был ли такой факт явно сохранен в этом снимке".
    /// </summary>
    /// <param name="fact">
    /// Факт-образец, который нужно найти в текущем снимке.
    /// </param>
    /// <returns>
    /// <c>true</c>, если в снимке есть равный факт; иначе <c>false</c>.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    /// Возникает, если факт-образец отсутствует.
    /// </exception>
    public bool ContainsExact(AssumptionFact fact)
    {
        ArgumentNullException.ThrowIfNull(fact);

        return Facts.Contains(fact);
    }


    /// <summary>
    /// Возвращает все явно сохраненные факты, субъект которых точно равен заданному выражению.
    /// Поиск ограничен только субъектом и намеренно не является математическим анализом выражения:
    /// метод не ищет эквивалентные формы, не применяет упрощение и не использует сведения из других фактов.
    /// Например, факты для <c>x</c> не будут найдены по субъекту <c>x + 0</c>, если текущее равенство Ast
    /// не считает эти выражения одинаковыми.
    ///
    /// Результат возвращается как новый защищенный список, а не как представление внутренней коллекции.
    /// Это сохраняет инвариант неизменяемого снимка: вызывающий код может читать найденные факты, но не может
    /// через результат поиска изменить порядок, добавить элемент или удалить факт из самого <see cref="AssumptionSet"/>.
    /// </summary>
    /// <param name="subject">
    /// Субъект, для которого нужно найти явно сохраненные факты.
    /// </param>
    /// <returns>
    /// Новый список фактов только для чтения с точно совпадающим субъектом. Если совпадений нет, возвращается пустой список.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    /// Возникает, если субъект поиска отсутствует.
    /// </exception>
    public IReadOnlyList<AssumptionFact> FindBySubject(AstNode subject)
    {
        ArgumentNullException.ThrowIfNull(subject);

        List<AssumptionFact> matchingFacts = new List<AssumptionFact>();

        // Просматриваем опубликованный снимок фактов линейно.
        // На первом этапе это намеренно простая операция контейнера: она не строит индекс, не запускает
        // каноникализацию и не пытается заменить будущий механизм вывода предположений.
        foreach (AssumptionFact fact in Facts)
        {
            // Сравниваем только субъект факта с заданным субъектом.
            // Остальные поля не проверяются, потому что задача метода — собрать все сведения о конкретном
            // выражении, например одновременно <c>x Positive True</c> и <c>x Real True</c>.
            if (Equals(fact.Subject, subject))
            {
                matchingFacts.Add(fact);
            }
        }

        if (matchingFacts.Count == 0)
        {
            return Array.Empty<AssumptionFact>();
        }

        return new ReadOnlyCollection<AssumptionFact>(matchingFacts);
    }


    /// <summary>
    /// Создает защищенную копию последовательности фактов.
    /// Метод намеренно выполняет проверку каждого элемента до публикации списка, потому что <c>null</c>
    /// внутри набора разрушил бы точный поиск и мог бы замаскировать ошибку построения предположений.
    /// </summary>
    /// <param name="facts">
    /// Исходная последовательность фактов.
    /// </param>
    /// <returns>
    /// Неизменяемое представление скопированной последовательности.
    /// </returns>
    /// <exception cref="ArgumentException">
    /// Возникает, если последовательность содержит отсутствующий факт.
    /// </exception>
    private static IReadOnlyList<AssumptionFact> CopyFacts(IEnumerable<AssumptionFact>? facts)
    {
        if (facts is null)
        {
            return Array.Empty<AssumptionFact>();
        }

        List<AssumptionFact> copiedFacts = new List<AssumptionFact>();

        foreach (AssumptionFact? fact in facts)
        {
            if (fact is null)
            {
                throw new ArgumentException("Набор предположений не должен содержать отсутствующие факты.", nameof(facts));
            }

            copiedFacts.Add(fact);
        }

        if (copiedFacts.Count == 0)
        {
            return Array.Empty<AssumptionFact>();
        }

        return new ReadOnlyCollection<AssumptionFact>(copiedFacts);
    }
}
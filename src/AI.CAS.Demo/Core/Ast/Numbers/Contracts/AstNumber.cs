using System.Text;

namespace AI.CAS.Core.Ast;

/// <summary>
/// Представляет базовое неизменяемое числовое значение, которое может храниться внутри <see cref="AstNumberNode"/>.
/// Используется в качестве базового типа для точных целых чисел <see cref="AstInteger"/>, канонических точных
/// рациональных чисел <see cref="AstRational"/> и приближенных десятичных значений <see cref="AstApproximateReal"/>
/// При этом базовый тип не хранит запись самого числа в том или ином формате. Эта задача делегируется производным
/// классам.
/// </summary>
public abstract class AstNumber : IEquatable<AstNumber>
{
    /// <summary>
    /// Проверяет равенство двух числовых значений.
    /// Равенство требует одинакового конкретного CLR-типа и одинаковых внутренних числовых данных, чтобы будущий
    /// рациональный тип не был случайно равен целому только из-за совпадения математического значения.
    /// </summary>
    /// <param name="other">
    /// Другое числовое значение Ast.
    /// </param>
    /// <returns>
    /// <see langword="true"/>, если значения имеют одинаковый конкретный тип и одинаковые данные.
    /// </returns>
    public bool Equals(AstNumber? other)
    {
        // Быстро подтверждаем равенство одной и той же неизменяемой ссылки.
        if (ReferenceEquals(this, other))
        {
            // Одна и та же ссылка не может различаться по числовому содержимому.
            return true;
        }

        // Отсутствующее значение не равно текущему числу.
        if (other is null)
        {
            // Возвращаем отрицательный результат для null.
            return false;
        }

        // Конкретный CLR-тип является частью числовой семантики и будущей совместимости.
        if (GetType() != other.GetType())
        {
            // У нас разный типы чисел =>
            return false;
        }

        // Тут получается типы сравниваемых чисел точно одинаковые, поэтому
        // делегируем дальнейшее сравнение конкретному числовому типу.
        return PayloadEquals(other);
    }


    /// <summary>
    /// Проверяет равенство текущего числового значения с произвольным объектом.
    /// Метод нужен для стандартных коллекций и согласован с типизированным сравнением <see cref="Equals(AstNumber?)"/>.
    /// </summary>
    /// <param name="obj">
    /// Произвольный объект, который может быть числовым значением AST.
    /// </param>
    /// <returns>
    /// <see langword="true"/>, если объект является равным числовым значением AST.
    /// </returns>
    public sealed override bool Equals(object? obj)
    {
        // Делегируем общей числовой логике, чтобы избежать двух расходящихся реализаций равенства.
        return Equals(obj as AstNumber);
    }


    /// <summary>
    /// Возвращает хеш-код, согласованный с числовым равенством.
    /// Хеш включает конкретный CLR-тип и собственные числовые данные, но не зависит от строковой записи числа.
    /// </summary>
    /// <returns>
    /// Хеш-код числового значения.
    /// </returns>
    public sealed override int GetHashCode()
    {
        // Создаем накопитель хеша для типа и внутренних данных.
        HashCode hashCode = new HashCode();

        // Добавляем конкретный тип, чтобы будущие виды чисел не смешивались в хеше.
        hashCode.Add(GetType());

        // Передаем накопитель конкретному типу для добавления внутренних числовых данных.
        AddPayloadHashCode(ref hashCode);

        // Возвращаем итоговый хеш стандартного формата .NET.
        return hashCode.ToHashCode();
    }


    /// <summary>
    /// Сравнивает собственные данные двух чисел одного конкретного CLR-типа.
    /// Конкретный наследник обязан проверять только свои данные, потому что базовый класс уже проверил тип.
    /// </summary>
    /// <param name="other">
    /// Другое числовое значение того же конкретного CLR-типа.
    /// </param>
    /// <returns>
    /// <see langword="true"/>, если собственные числовые данные равны.
    /// </returns>
    protected abstract bool PayloadEquals(AstNumber other);


    /// <summary>
    /// Добавляет собственные числовые данные в накопитель хеша.
    /// Конкретный наследник обязан использовать те же данные, которые участвуют в <see cref="PayloadEquals"/>.
    /// </summary>
    /// <param name="hashCode">
    /// Накопитель хеша, в который нужно добавить числовые данные.
    /// </param>
    protected abstract void AddPayloadHashCode(ref HashCode hashCode);


    /// <summary>
    /// Печатает число в структурной отладочной форме <see cref="AstDebugFormatter"/> независимо от культуры потока.
    /// Конкретный тип печатает ровно те данные, которые участвуют в <see cref="PayloadEquals"/>. Базовая реализация
    /// печатает имя CLR-типа: это запасной вариант для вида числа, который еще не определил собственную форму.
    /// </summary>
    /// <param name="builder">
    /// Буфер формы.
    /// </param>
    internal virtual void AppendDebugPayload(StringBuilder builder)
    {
        builder.Append(GetType().Name);
    }
}



namespace AI.CAS.Core.Assumptions;

/// <summary>
/// Представляет трехзначное логическое значение предположения.
/// Трехзначная логика необходима для корректной CAS-архитектуры, потому что отсутствие доказательства
/// не является доказательством ложности и не должно разрешать опасные алгебраические преобразования.
/// </summary>
public enum AssumptionTruthValue
{
    /// <summary>
    /// Утверждение доказанно ложно в текущем наборе предположений.
    /// </summary>
    False = -1,


    /// <summary>
    /// Истинность утверждения неизвестна текущему механизму предположений.
    /// Это безопасное значение по умолчанию.
    /// </summary>
    Unknown = 0,


    /// <summary>
    /// Утверждение доказанно истинно в текущем наборе предположений.
    /// </summary>
    True = 1
}

namespace AI.CAS.Core.Assumptions;

/// <summary>
/// Перечисляет внутренние виды результата одного правила знаний.
/// Эти состояния намеренно богаче публичной трехзначной логики, потому что публичный <see cref="AssumptionTruthValue.Unknown"/>
/// объединяет несколько разных причин неизвестности.
/// </summary>
internal enum AssumptionRuleResultKind
{
    /// <summary>
    /// Поставщик не относится к запросу или не нашел релевантного знания.
    /// Такое молчание не должно ослаблять доказательство другого поставщика.
    /// </summary>
    NoAnswer = 0,


    /// <summary>
    /// Поставщик безопасно доказал истинность или ложность утверждения.
    /// Конкретное значение хранится отдельно в <see cref="AssumptionProviderResult.ProvedTruthValue"/>.
    /// </summary>
    Proved = 1,


    /// <summary>
    /// Поставщик был применим, но его предпосылки не были доказаны или доказательство было технически прервано.
    /// Это не математический конфликт и не должно подавлять определенный ответ другого поставщика.
    /// </summary>
    Inconclusive = 2,


    /// <summary>
    /// Поставщик обнаружил несовместимые определенные свидетельства.
    /// Конфликт проецируется наружу как Unknown, но внутри остается отдельным состоянием.
    /// </summary>
    Conflict = 3
}
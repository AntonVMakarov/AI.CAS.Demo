namespace AI.CAS.Core.Assumptions;

/// <summary>
/// Представляет минимальный типизированный скалярный интервал.
/// Интервал является семантическими данными слоя предположений, а не строкой, не узлом отображения и не набором
/// произвольных неравенств. Его ответственность намеренно узкая: хранить нижнюю и верхнюю границы, различать
/// открытые, закрытые и неограниченные стороны и быть стабильным ключом для <see cref="AssumptionAtom"/>.
/// </summary>
/// <remarks>
/// <para>
/// Модуль упрощения использует этот тип например при осуществлении преобразования
/// <c>arcsin(sin(x)) -> x</c> которое корректно только на главном интервале <c>[-pi/2, pi/2]</c>, а преобразование
/// <c>arctg(tg(x)) -> x</c> требует открытый интервал <c>(-pi/2, pi/2)</c>. Открытость последнего интервала
/// одновременно исключает концевые полюса тангенса.
/// </para>
/// <para>
/// Тип не является общей интервальной арифметикой. Он не складывает интервалы, не решает неравенства, 
/// и не выводит принадлежность сложных выражений. Все доказательства выполняются отдельными поставщиками предположений.
/// </para>
/// </remarks>
public sealed record ScalarInterval
{
    /// <summary>
    /// Создает типизированный интервал из двух уже созданных границ.
    /// Конструктор сохраняет порядок нижняя-верхняя как часть математической модели. Он не пытается доказать,
    /// что нижняя граница меньше верхней.
    /// </summary>
    /// <param name="lowerBound">
    /// Нижняя граница интервала.
    /// </param>
    /// <param name="upperBound">
    /// Верхняя граница интервала.
    /// </param>
    /// <exception cref="ArgumentNullException">
    /// Возникает, если одна из границ отсутствует.
    /// </exception>
    public ScalarInterval(ScalarIntervalBound lowerBound, ScalarIntervalBound upperBound)
    {
        // Проверяем нижнюю границу до сохранения.
        ArgumentNullException.ThrowIfNull(lowerBound);

        // Проверяем верхнюю границу до сохранения.
        ArgumentNullException.ThrowIfNull(upperBound);

        // Сохраняем нижнюю границу интервала.
        LowerBound = lowerBound;

        // Сохраняем верхнюю границу интервала.
        UpperBound = upperBound;
    }


    /// <summary>
    /// Возвращает нижнюю границу интервала.
    /// </summary>
    public ScalarIntervalBound LowerBound { get; }


    /// <summary>
    /// Возвращает верхнюю границу интервала.
    /// </summary>
    public ScalarIntervalBound UpperBound { get; }


    /// <summary>
    /// Возвращает признак интервала с двумя конечными границами.
    /// Такие интервалы можно узко трактовать как подмножества конечной вещественной прямой, когда есть
    /// явный истинный факт <c>InInterval(x, interval)</c>.
    /// </summary>
    public bool HasFiniteEndpoints => !LowerBound.IsUnbounded && !UpperBound.IsUnbounded;
}

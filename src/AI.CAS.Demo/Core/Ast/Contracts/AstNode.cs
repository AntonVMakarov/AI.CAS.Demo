using System.Collections.Immutable;
using System.Diagnostics;
using System.Text;

namespace AI.CAS.Core.Ast;

/// <summary>
/// Представляет базовый узел дерева выражений.
/// Этот тип отвечает только за общую структурную форму дерева: неизменяемый упорядоченный список детей,
/// индексный доступ к детям, признак листа, пересборку узла с новыми детьми и явное структурное сравнение.
/// Математический смысл узла определяется конкретным CLR-типом наследника, например <see cref="AstPlusNode"/>
/// или <see cref="AstSinNode"/>, поэтому базовый тип намеренно не содержит общего поля вида операции,
/// общего поля семантического значения, парсинга, упрощения, канонизации, вывода формул или правил преобразования.
/// </summary>
/// <remarks>
/// <see cref="ToString"/> возвращает структурную отладочную форму дерева (<see cref="AstDebugFormatter"/>), например
/// <c>Plus[Times[2, x], 1]</c>. Это инструмент разработчика для сообщений тестов и отладчика, а не текст для
/// учащегося: пользовательский вывод строят рендереры слоя <c>Presentation</c>.
/// </remarks>
[DebuggerDisplay("{DebuggerDisplayText,nq}")]
public abstract class AstNode : IEquatable<AstNode>
{
    /// <summary>
    /// Наибольшая длина структурной формы в строке отладчика: длиннее обрезается, чтобы отладчик оставался быстрым
    /// на огромных выражениях.
    /// </summary>
    private const int DebuggerDisplayMaxLength = 200;


    /// <summary>
    /// Сторожевое значение кэша структурного хеша: хеш еще не вычислен.
    /// Если настоящий структурный хеш случайно равен этому значению, в кэш и наружу отдается
    /// <see cref="SentinelCollisionReplacementHashCode"/>, поэтому сторож никогда не совпадает с опубликованным хешем.
    /// </summary>
    private const int HashCodeNotComputed = 0;


    /// <summary>
    /// Значение, которое публикуется вместо вычисленного хеша, совпавшего со сторожевым <see cref="HashCodeNotComputed"/>.
    /// Замена детерминирована, поэтому структурно равные деревья по-прежнему получают равные хеши.
    /// </summary>
    private const int SentinelCollisionReplacementHashCode = 1;


    /// <summary>
    /// Хранит лениво вычисленный структурный хеш неизменяемого дерева или <see cref="HashCodeNotComputed"/>.
    /// </summary>
    /// <remarks>
    /// Это единственное изменяемое поле узла, и оно не является наблюдаемым состоянием: хеш полностью определяется
    /// неизменяемыми типом, собственной нагрузкой и детьми, поэтому запись кэша не меняет ни равенство, ни хеш.
    /// Гонка при первом вычислении безопасна: запись <see cref="int"/> атомарна, а два потока, вычислившие хеш
    /// одновременно, записывают одно и то же значение. Поле намеренно не <see langword="volatile"/>: поток, который
    /// не увидел чужую запись, просто вычислит тот же хеш еще раз.
    /// </remarks>
    private int _structuralHashCode;


    /// <summary>
    /// Возвращает неизменяемых детей узла в том порядке, в котором они входят в исходную структуру выражения.
    /// Порядок является частью сырого структурного контракта: выражения <c>a+b</c> и <c>b+a</c> не считаются
    /// одинаковыми на этом уровне, даже если поздняя математическая канонизация сможет доказать их эквивалентность.
    /// </summary>
    public abstract ImmutableArray<AstNode> Children { get; }


    /// <summary>
    /// Возвращает количество дочерних узлов в общей упорядоченной коллекции <see cref="Children"/>.
    /// Свойство является коротким псевдонимом арности типизированного AST для мигрируемых алгоритмов фазы 5.5, которым
    /// раньше приходилось читать количество детей старого дерева через legacy-поверхность. Значение не хранится
    /// отдельно и всегда вычисляется из неизменяемой коллекции детей, поэтому оно не может разойтись с реальной
    /// структурой узла и не вводит канал мутации.
    /// </summary>
    public int Count
    {
        get
        {
            // Возвращаем длину единственного структурного списка детей, чтобы арность всегда совпадала с Children.
            return Children.Length;
        }
    }


    /// <summary>
    /// Возвращает ребенка по индексу из упорядоченной коллекции <see cref="Children"/>.
    /// Индексатор является коротким общим API для обходов и перестроений, которые не хотят знать конкретный тип узла.
    /// </summary>
    /// <param name="index">
    /// Нулевая позиция ребенка в упорядоченной коллекции детей.
    /// </param>
    /// <returns>
    /// Дочерний узел на указанной позиции.
    /// </returns>
    public AstNode this[int index]
    {
        get
        {
            // Делегируем проверку диапазона в ImmutableArray, чтобы контракт исключения совпадал с обычным индексатором коллекции.
            return Children[index];
        }
    }


    /// <summary>
    /// Возвращает признак листового узла.
    /// Листом является узел без детей, например число или переменная; алгоритм общего обхода может завершать рекурсию
    /// по этому признаку, не вводя список всех атомарных типов.
    /// </summary>
    public bool IsLeaf
    {
        get
        {
            // Используем свойство ImmutableArray, потому что оно явно выражает отсутствие детей без выделения новой коллекции.
            return Children.IsEmpty;
        }
    }


    /// <summary>
    /// Создает новый узел того же конкретного математического типа с указанными детьми.
    /// Реализация обязана сохранить порядок детей, проверить арность, не менять исходный объект и не выполнять
    /// математическое упрощение. Например, перестройка суммы с детьми <c>x</c> и <c>0</c> должна вернуть узел суммы,
    /// а не переменную <c>x</c>.
    /// </summary>
    /// <param name="children">
    /// Новый упорядоченный набор детей, который должен удовлетворять арности конкретного типа узла.
    /// </param>
    /// <returns>
    /// Новый узел того же конкретного CLR-типа с переданными детьми.
    /// </returns>
    public abstract AstNode WithChildren(ImmutableArray<AstNode> children);


    /// <summary>
    /// Создает новый узел того же конкретного математического типа с указанными детьми, переданными обычным массивом.
    /// Перегрузка является удобным маршрутом для generic traversal-кода Phase 5.5, который накапливает детей в массиве
    /// ради индексного обновления и затем должен вернуться к единому immutable-контракту <see cref="WithChildren(ImmutableArray{AstNode})"/>.
    /// Метод не выполняет упрощение, сортировку, legacy-конвертацию или изменение семантики; он только копирует массив
    /// в <see cref="ImmutableArray{T}"/> и делегирует основному контракту пересборки.
    /// </summary>
    /// <param name="children">
    /// Новый упорядоченный набор детей, который будет скопирован в неизменяемую коллекцию.
    /// </param>
    /// <returns>
    /// Новый узел того же concrete CLR type с переданными детьми.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    /// Возникает, если массив детей отсутствует.
    /// </exception>
    public AstNode WithChildren(params AstNode[] children)
    {
        // Проверяем сам массив до копирования, чтобы вызывающий generic traversal получил явную ошибку аргумента.
        ArgumentNullException.ThrowIfNull(children);

        // Копируем массив в immutable-коллекцию, чтобы дальнейшие изменения массива вызывающего кода не затронули AST.
        ImmutableArray<AstNode> immutableChildren = ImmutableArray.Create(children);

        // Делегируем конкретному узлу проверку арности, null-элементов и собственную стратегию пересборки.
        return WithChildren(immutableChildren);
    }


    /// <summary>
    /// Проверяет структурное равенство двух узлов AST.
    /// Равенство требует одинакового конкретного CLR-типа, одинаковых семантических данных и рекурсивно равных детей
    /// в том же порядке. Такая семантика намеренно не является коммутативной для сложения и умножения.
    /// </summary>
    /// <param name="other">
    /// Другой узел, с которым сравнивается текущий объект.
    /// </param>
    /// <returns>
    /// <see langword="true"/>, если оба узла имеют одинаковый тип, одинаковые данные и одинаковую упорядоченную структуру.
    /// </returns>
    public bool Equals(AstNode? other)
    {
        // Быстро подтверждаем равенство одной и той же ссылки, потому что неизменяемые узлы не меняют состояние после создания.
        if (ReferenceEquals(this, other))
        {
            // Одинаковая ссылка всегда означает одинаковую структуру.
            return true;
        }

        // Отсутствующий второй узел не может быть структурно равен текущему узлу.
        if (other is null)
        {
            // Возвращаем отрицательный результат для сравнения с null.
            return false;
        }

        // Конкретный CLR-тип является главным семантическим дискриминатором нового дерева.
        if (GetType() != other.GetType())
        {
            // Разные типы вроде синуса и косинуса не равны даже при одинаковом аргументе.
            return false;
        }

        // Если оба хеша уже вычислены и различаются, деревья заведомо неравны: хеш согласован с равенством. Хеш здесь
        // не вычисляется, чтобы сравнение не стало дороже прежнего для деревьев, которые еще ни разу не хешировались.
        int cachedHashCode = _structuralHashCode;
        int otherCachedHashCode = other._structuralHashCode;
        if (cachedHashCode != HashCodeNotComputed
            && otherCachedHashCode != HashCodeNotComputed
            && cachedHashCode != otherCachedHashCode)
        {
            return false;
        }

        // Сравниваем собственные семантические данные узла, например имя переменной или точное целое число.
        if (!PayloadEquals(other))
        {
            // Разные данные листа или именованной функции нарушают структурное равенство.
            return false;
        }

        // Берем детей текущего узла один раз, чтобы дальнейшие проверки читали одну и ту же неизменяемую коллекцию.
        ImmutableArray<AstNode> children = Children;

        // Берем детей второго узла один раз для симметричной проверки структуры.
        ImmutableArray<AstNode> otherChildren = other.Children;

        // Сравниваем количество детей до рекурсии, потому что разная арность уже доказывает неравенство.
        if (children.Length != otherChildren.Length)
        {
            // Возвращаем отрицательный результат без лишнего обхода.
            return false;
        }

        // Обходим детей по индексам, потому что порядок является обязательной частью сырого AST.
        for (int index = 0; index < children.Length; index++)
        {
            // Сравниваем соответствующих детей рекурсивно через тот же контракт AstNode.Equals.
            if (!children[index].Equals(otherChildren[index]))
            {
                // Первое несовпадение в упорядоченной позиции делает все дерево неравным.
                return false;
            }
        }

        // Если тип, данные и все дети совпали, узлы структурно равны.
        return true;
    }


    /// <summary>
    /// Проверяет структурное равенство текущего узла с произвольным объектом.
    /// Метод нужен для согласованности стандартных коллекций .NET с явным контрактом <see cref="Equals(AstNode?)"/>.
    /// </summary>
    /// <param name="obj">
    /// Произвольный объект, который может быть узлом AST.
    /// </param>
    /// <returns>
    /// <see langword="true"/>, если объект является структурно равным узлом AST.
    /// </returns>
    public sealed override bool Equals(object? obj)
    {
        // Делегируем типизированному сравнению, чтобы вся логика равенства находилась в одном месте.
        return Equals(obj as AstNode);
    }


    /// <summary>
    /// Возвращает хеш-код, согласованный с упорядоченным структурным равенством.
    /// В хеш включаются конкретный CLR-тип, семантические данные текущего узла и дети в исходном порядке.
    /// Хеш намеренно не зависит от старых весов, строкового вывода или будущей математической канонизации.
    /// </summary>
    /// <remarks>
    /// Хеш вычисляется один раз на узел и кэшируется (фаза CR2): дерево неизменяемо, поэтому значение не может
    /// устареть. Хеш детей тоже кэширован, поэтому полный обход выполняется только при первом вызове, а для общих
    /// поддеревьев (ориентированного ациклического графа узлов) — один раз на каждый различный узел. Вызов безопасен
    /// из нескольких потоков.
    /// </remarks>
    /// <returns>
    /// Хеш-код текущего неизменяемого дерева.
    /// </returns>
    public sealed override int GetHashCode()
    {
        int cachedHashCode = _structuralHashCode;
        if (cachedHashCode != HashCodeNotComputed)
        {
            return cachedHashCode;
        }

        int computedHashCode = ComputeStructuralHashCode();

        // Вычисленное значение, совпавшее со сторожем, заменяется постоянным, иначе такой узел пересчитывал бы хеш
        // при каждом вызове.
        if (computedHashCode == HashCodeNotComputed)
        {
            computedHashCode = SentinelCollisionReplacementHashCode;
        }

        _structuralHashCode = computedHashCode;
        return computedHashCode;
    }


    /// <summary>
    /// Вычисляет структурный хеш узла без обращения к кэшу текущего узла.
    /// Хеши детей берутся через их <see cref="GetHashCode"/> и потому тоже кэшируются.
    /// </summary>
    /// <returns>
    /// Структурный хеш, который может совпасть со сторожевым значением; замену выполняет <see cref="GetHashCode"/>.
    /// </returns>
    private int ComputeStructuralHashCode()
    {
        // Создаем накопитель хеша, который корректно объединяет несколько разнородных компонентов.
        HashCode hashCode = new();

        // Добавляем конкретный CLR-тип, чтобы разные математические узлы с одинаковыми детьми имели разные хеши.
        hashCode.Add(GetType());

        // Позволяем наследнику добавить собственные семантические данные, например имя переменной.
        AddPayloadHashCode(ref hashCode);

        // Берем детей один раз, чтобы порядок обхода хеша совпадал с порядком сравнения.
        ImmutableArray<AstNode> children = Children;

        // Добавляем число детей, чтобы короткие и длинные структуры не смешивались при одинаковом префиксе.
        hashCode.Add(children.Length);

        // Добавляем каждого ребенка в исходном порядке, потому что порядок является частью равенства.
        foreach (AstNode child in children)
        {
            // Добавляем дочерний узел через его собственный структурный хеш.
            hashCode.Add(child);
        }

        // Завершаем накопление и возвращаем стандартный int-хеш для словарей и множеств .NET.
        return hashCode.ToHashCode();
    }


    /// <summary>
    /// Возвращает структурную отладочную форму дерева, например <c>Plus[Times[2, x], 1]</c>.
    /// Форма точно отражает структуру: деревья <c>Minus[x, 1]</c>, <c>Plus[x, UnaryMinus[1]]</c> и <c>Plus[x, -1]</c>
    /// печатаются по-разному, хотя человеку все три показываются как <c>x − 1</c>. Метод запечатан, как
    /// <see cref="Equals(object?)"/> и <see cref="GetHashCode"/>: конкретные узлы не переопределяют его, а добавляют
    /// собственные данные через <see cref="AppendDebugPayload"/>.
    /// </summary>
    /// <remarks>
    /// Только для разработчика: сообщения тестов, отладчик, диагностические журналы. Никогда не используйте эту форму
    /// для текста, который видит учащийся. Форма не зависит от культуры потока и не переполняет стек на глубоких
    /// деревьях. Отмена не поддерживается: форма строится за один линейный проход.
    /// </remarks>
    /// <returns>
    /// Полная структурная форма дерева.
    /// </returns>
    public sealed override string ToString()
    {
        return AstDebugFormatter.Shared.Format(this);
    }


    /// <summary>
    /// Возвращает обрезанную структурную форму для строки отладчика.
    /// </summary>
    private string DebuggerDisplayText => AstDebugFormatter.Shared.Format(this, DebuggerDisplayMaxLength);


    /// <summary>
    /// Добавляет собственную нагрузку узла в структурную отладочную форму <see cref="AstDebugFormatter"/>.
    /// Базовая реализация ничего не добавляет: у большинства узлов нет данных кроме типа и детей. Наследник с
    /// собственными данными печатает ровно те данные, которые участвуют в <see cref="PayloadEquals"/>, чтобы
    /// структурно разные узлы не печатались одинаково.
    /// </summary>
    /// <param name="builder">
    /// Буфер формы, в который нужно дописать нагрузку без разделителей вокруг нее.
    /// </param>
    internal virtual void AppendDebugPayload(StringBuilder builder)
    {
    }


    /// <summary>
    /// Возвращает признак того, что лист печатается одной нагрузкой без вида узла: переменная — именем <c>x</c>, число —
    /// значением <c>2</c>. Для остальных узлов вид печатается всегда, например <c>RealRootOf[{-2, 0, 1}, 1]</c>.
    /// </summary>
    internal virtual bool PrintsDebugPayloadWithoutKind => false;


    /// <summary>
    /// Сравнивает собственные семантические данные двух узлов одного конкретного CLR-типа.
    /// Базовая реализация возвращает равенство для узлов без дополнительных данных, например для синуса или степени,
    /// где весь смысл уже выражен типом и детьми.
    /// </summary>
    /// <param name="other">
    /// Другой узел того же конкретного CLR-типа.
    /// </param>
    /// <returns>
    /// <see langword="true"/>, если собственные данные двух узлов равны.
    /// </returns>
    protected virtual bool PayloadEquals(AstNode other)
    {
        // Узлы без собственных семантических данных считаются равными после проверки конкретного типа.
        return true;
    }


    /// <summary>
    /// Добавляет собственные семантические данные узла в накопитель хеша.
    /// Базовая реализация ничего не добавляет, потому что у большинства операторных узлов нет данных кроме типа и детей.
    /// </summary>
    /// <param name="hashCode">
    /// Накопитель хеша, в который наследник может добавить собственные данные.
    /// </param>
    protected virtual void AddPayloadHashCode(ref HashCode hashCode)
    {
        // Базовый узел не имеет собственной семантической нагрузки сверх конкретного типа и детей.
    }


    /// <summary>
    /// Сравнивает собственную семантическую нагрузку узлов для внутренних обходов типизированного AST, которым нужна
    /// та же семантика собственной нагрузки, что и у базового <see cref="Equals(AstNode?)"/>, но которые обходят детей сами.
    /// Метод существует для отменяемых и стековых сравнителей: они должны регулярно проверять токен отмены между
    /// посещениями узлов, но не имеют права повторно реализовывать закрытый список типов с собственной нагрузкой.
    /// Вызывающий код обязан сначала проверить совпадение конкретного CLR-типа и отдельно сравнить упорядоченных детей.
    /// </summary>
    /// <param name="other">
    /// Другой узел того же конкретного CLR-типа.
    /// </param>
    /// <returns>
    /// <see langword="true"/>, если собственные семантические данные текущего узла совпадают с данными другого узла.
    /// </returns>
    internal bool HasSameStructuralPayload(AstNode other)
    {
        // Проверяем аргумент на null, потому что внутренний сравнитель всегда должен сравнивать два реальных узла.
        ArgumentNullException.ThrowIfNull(other);

        // Делегируем виртуальному контракту собственной нагрузки, чтобы будущие наследники AST не требовали правки каждого обхода.
        return PayloadEquals(other);
    }


    /// <summary>
    /// Проверяет один дочерний узел на отсутствие null.
    /// Метод централизует диагностику, чтобы все конструкторы AST одинаково отвергали неполные деревья.
    /// </summary>
    /// <param name="child">
    /// Проверяемый дочерний узел.
    /// </param>
    /// <param name="parameterName">
    /// Имя параметра, переданного публичному API.
    /// </param>
    /// <returns>
    /// Тот же дочерний узел, если он прошел проверку.
    /// </returns>
    protected static AstNode ValidateChild(AstNode? child, string parameterName)
    {
        // Проверяем null на границе построения, чтобы в дерево не попадали отсутствующие ветви.
        if (child is null)
        {
            // Сообщаем имя параметра, потому что вызвавшему коду важно быстро найти ошибочный аргумент.
            throw new ArgumentNullException(parameterName);
        }

        // Возвращаем проверенный узел без копирования, потому что сам узел неизменяем.
        return child;
    }


    /// <summary>
    /// Проверяет упорядоченную коллекцию детей на наличие значения, отсутствие null-элементов и точную арность.
    /// Метод используется фиксированными унарными и бинарными узлами при пересборке через <see cref="WithChildren"/>.
    /// </summary>
    /// <param name="children">
    /// Проверяемая неизменяемая коллекция детей.
    /// </param>
    /// <param name="expectedCount">
    /// Требуемое количество детей для конкретного типа узла.
    /// </param>
    /// <param name="parameterName">
    /// Имя параметра публичного API.
    /// </param>
    /// <returns>
    /// Та же коллекция, если она прошла проверки арности и null-элементов.
    /// </returns>
    protected static ImmutableArray<AstNode> ValidateChildren(ImmutableArray<AstNode> children, int expectedCount, string parameterName)
    {
        // Проверяем значение по умолчанию ImmutableArray, потому что оно не представляет корректную пустую коллекцию детей.
        if (children.IsDefault)
        {
            // Сообщаем об отсутствующей коллекции как об ошибке аргумента.
            throw new ArgumentException("Коллекция детей AST должна быть явно создана.", parameterName);
        }

        // Проверяем точную арность, чтобы математический смысл узла с фиксированной арностью не распался.
        if (children.Length != expectedCount)
        {
            // Сообщаем ожидаемое количество детей, потому что ошибка почти всегда находится в логике вызывающей пересборки.
            throw new ArgumentException($"Ожидалось ровно {expectedCount} дочерних узлов.", parameterName);
        }

        // Проверяем каждый элемент, чтобы неизменяемая коллекция не скрывала null-ребенка.
        for (int index = 0; index < children.Length; index++)
        {
            // Если ребенок отсутствует, структура дерева является неполной и должна быть отвергнута.
            if (children[index] is null)
            {
                // Используем ArgumentException, потому что null находится внутри коллекционного аргумента.
                throw new ArgumentException($"Дочерний узел с индексом {index} не должен быть null.", parameterName);
            }
        }

        // Возвращаем проверенную коллекцию без копирования, потому что ImmutableArray уже неизменяем.
        return children;
    }


    /// <summary>
    /// Проверяет упорядоченную коллекцию детей на наличие значения, отсутствие null-элементов и минимальную арность.
    /// Метод используется n-арными узлами, где допустимы два и более операнда.
    /// </summary>
    /// <param name="children">
    /// Проверяемая неизменяемая коллекция детей.
    /// </param>
    /// <param name="minimumCount">
    /// Минимально допустимое количество детей.
    /// </param>
    /// <param name="parameterName">
    /// Имя параметра публичного API.
    /// </param>
    /// <returns>
    /// Та же коллекция, если она прошла проверки минимальной арности и null-элементов.
    /// </returns>
    protected static ImmutableArray<AstNode> ValidateChildrenAtLeast(ImmutableArray<AstNode> children, int minimumCount, string parameterName)
    {
        // Проверяем значение по умолчанию ImmutableArray, потому что оно отличается от корректной пустой коллекции.
        if (children.IsDefault)
        {
            // Сообщаем об отсутствующей коллекции как об ошибке структурного аргумента.
            throw new ArgumentException("Коллекция детей AST должна быть явно создана.", parameterName);
        }

        // Проверяем минимальную арность n-арного узла, например сложение не должно состоять из одного слагаемого.
        if (children.Length < minimumCount)
        {
            // Сообщаем минимальное количество, чтобы ошибка построения была очевидной.
            throw new ArgumentException($"Ожидалось не менее {minimumCount} дочерних узлов.", parameterName);
        }

        // Проверяем каждый элемент коллекции на отсутствие null.
        for (int index = 0; index < children.Length; index++)
        {
            // Значение null у ребенка разрушило бы инвариант полного дерева.
            if (children[index] is null)
            {
                // Используем ArgumentException, потому что некорректен элемент внутри коллекции.
                throw new ArgumentException($"Дочерний узел с индексом {index} не должен быть null.", parameterName);
            }
        }

        // Возвращаем проверенную неизменяемую коллекцию.
        return children;
    }


    /// <summary>
    /// Проверяет упорядоченную коллекцию детей без ограничения снизу.
    /// Метод нужен для именованных пользовательских функций, где нулевая арность может быть осмысленной формой,
    /// но сама коллекция и каждый ее элемент все равно должны быть корректными.
    /// </summary>
    /// <param name="children">
    /// Проверяемая неизменяемая коллекция детей.
    /// </param>
    /// <param name="parameterName">
    /// Имя параметра публичного API.
    /// </param>
    /// <returns>
    /// Та же коллекция, если она явно создана и не содержит null.
    /// </returns>
    protected static ImmutableArray<AstNode> ValidateChildren(ImmutableArray<AstNode> children, string parameterName)
    {
        // Проверяем значение по умолчанию ImmutableArray, потому что оно не является явной корректной коллекцией аргументов.
        if (children.IsDefault)
        {
            // Сообщаем об ошибке коллекционного аргумента.
            throw new ArgumentException("Коллекция детей AST должна быть явно создана.", parameterName);
        }

        // Проверяем каждый элемент, даже если коллекция может быть пустой.
        for (int index = 0; index < children.Length; index++)
        {
            // Значение null у аргумента пользовательской функции сделало бы дерево неполным.
            if (children[index] is null)
            {
                // Используем ArgumentException, потому что null находится внутри переданной коллекции.
                throw new ArgumentException($"Дочерний узел с индексом {index} не должен быть null.", parameterName);
            }
        }

        // Возвращаем проверенную коллекцию без дополнительного выделения.
        return children;
    }


    /// <summary>
    /// Проверяет имя переменной или пользовательской функции.
    /// Фаза 1 не вводит политику парсера и не нормализует имена, но отвергает null, пустую строку и строку
    /// только из пробельных символов, потому что такие имена не могут быть надежным атомарным символом.
    /// </summary>
    /// <param name="name">
    /// Проверяемое имя.
    /// </param>
    /// <param name="parameterName">
    /// Имя параметра публичного API.
    /// </param>
    /// <returns>
    /// Исходное имя без обрезки и нормализации, если оно прошло минимальную проверку.
    /// </returns>
    protected static string ValidateName(string? name, string parameterName)
    {
        // Проверяем минимальный контракт имени без ввода парсерной политики будущих фаз.
        if (string.IsNullOrWhiteSpace(name))
        {
            // Используем ArgumentException и для null, и для пустых имен, чтобы публичный контракт имени был единым.
            throw new ArgumentException("Имя AST-символа должно содержать хотя бы один непробельный символ.", parameterName);
        }

        // Возвращаем имя в точности как передал вызывающий код, потому что фаза 1 не занимается нормализацией.
        return name;
    }


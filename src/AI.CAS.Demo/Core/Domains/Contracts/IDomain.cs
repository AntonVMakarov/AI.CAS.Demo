namespace AI.CAS.Core.Domains;

/// <summary>
/// Интерфейс представляет собой математическую область.
/// Интерфейс намеренно мал: он фиксирует только вид области и человекочитаемое техническое имя,
/// не добавляя поведения доказательства, решения уравнений или упрощения выражений.
/// </summary>
public interface IDomain
{
    /// <summary>
    /// Возвращает общий вид математической области.
    /// Это значение удобно для маршрутизации фасадов, но само по себе не доказывает принадлежность
    /// конкретного выражения области.
    /// </summary>
    DomainKind Kind { get; }


    /// <summary>
    /// Возвращает отображаемое техническое имя области.
    /// Имя предназначено для диагностики, журналирования и отладочного вывода, а не для математического
    /// парсинга или локализованного образовательного текста.
    /// </summary>
    string DisplayName { get; }
}
